fn main() {
    // initial numbers
    let a = 32;
    let b = 20;

    // greater than
    let res = a > b;
    println!("A > B: {}", res);

    // less than
    let res = a < b;
    println!("A < B: {}", res);

    // greater than or equal
    let res = a >= b;
    println!("A >= B: {}", res);

    // less than or equal
    let res = a <= b;
    println!("A <= B: {}", res);

    // equal
    let res = a == b;
    println!("A == B: {}", res);

    // not equal
    let res = a != b;
    println!("A != B: {}", res);
}
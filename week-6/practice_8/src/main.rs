fn main() {
    // initial numbers
    let num1 = 10;
    let num2 = 2;

    // addition
    let result = num1 + num2;
    println!("Sum: {}", result);

    // subtraction
    let result = num1 - num2;
    println!("Difference: {}", result);

    // multiplication
    let result = num1 * num2;
    println!("Product: {}", result);

    // division
    let result = num1 / num2;
    println!("Quotient: {}", result);

    // remainder
    let result = num1 % num2;
    println!("Remainder: {}", result);
}